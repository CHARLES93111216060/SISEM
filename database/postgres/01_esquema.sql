-- =====================================================================================
-- SISEM · Esquema PostgreSQL (migrado desde MariaDB, según el diagrama ER del proyecto)
-- Ejecutar UNA vez en la base vacía de Render:  DBeaver → Editor SQL → Alt+X (Ejecutar script)
--
-- Decisiones:
--   * id  → INTEGER IDENTITY "BY DEFAULT": permite cargar los ids originales y después
--           seguir autonumerando (ver 02_ajustar_secuencias.sql).
--   * Tipos y NOT NULL verificados contra information_schema de la MariaDB real:
--     int(11) → integer · text → text · longtext → text · datetime → timestamp.
--   * reportes.reporte → TEXT, igual que el longtext de MariaDB.
-- =====================================================================================
BEGIN;

CREATE TABLE marcas (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand text NOT NULL
);

CREATE TABLE tipo_equipo (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipo text NOT NULL
);

CREATE TABLE mantenimientos (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_mantenimiento text NOT NULL
);

CREATE TABLE clientes (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             text NOT NULL,
    nit                text NOT NULL,
    direccion          text NOT NULL,
    telefono           text NOT NULL,
    representante_legal text NOT NULL,
    correo             text NOT NULL
);

CREATE TABLE personal (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    text NOT NULL,
    documento text NOT NULL,
    cargo     text NOT NULL,
    profesion text NOT NULL,
    correo    text NOT NULL
);

CREATE TABLE inventario (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo                integer REFERENCES tipo_equipo (id),
    marca                    integer REFERENCES marcas (id),
    lote                     text NOT NULL,
    serie                    text NOT NULL,
    serial_inventario_interno text NOT NULL,
    id_cliente               integer NOT NULL REFERENCES clientes (id),
    riesgo                   text NOT NULL
);

CREATE TABLE reportes (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tecnico integer NOT NULL REFERENCES personal (id),
    id_cliente integer NOT NULL REFERENCES clientes (id),
    id_equipo  integer NOT NULL REFERENCES tipo_equipo (id),
    fecha      timestamp NOT NULL,
    reporte    text      NOT NULL
);

-- Índices para el historial, el tablero y las consultas por cliente/equipo/técnico
CREATE INDEX reportes_fecha_idx      ON reportes (fecha);
CREATE INDEX reportes_id_cliente_idx ON reportes (id_cliente);
CREATE INDEX reportes_id_equipo_idx  ON reportes (id_equipo);
CREATE INDEX reportes_id_tecnico_idx ON reportes (id_tecnico);
CREATE INDEX inventario_id_cliente_idx ON inventario (id_cliente);
CREATE INDEX inventario_id_equipo_idx  ON inventario (id_equipo);

COMMIT;
